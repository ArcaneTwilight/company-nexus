/** Look up a flag emoji by country name; returns a globe if not found. */
export function getCountryFlag(country: string): string {
  return COUNTRY_FLAGS[country.trim()] ?? "\u{1F310}";
}

/** All country names available in the flag repository, sorted alphabetically. */
export function availableCountries(): string[] {
  return Object.keys(COUNTRY_FLAGS).sort();
}
